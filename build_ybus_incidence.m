% Формирование матрицы узловых проводимостей Y_bus
% через обобщённую матрицу инцидентности
% Выражения (7.41)–(7.58)
% на вход передаются:
%   n_bus    — количество узлов сети
%   A_ob     — обобщённая матрица инцидентности, размер m × n
%   Y_br     — вектор-столбец проводимостей ветвей, размер m × 1
%   Y_shunt  — вектор-столбец суммарных шунтирующих проводимостей узлов,
%              размер n × 1
% на выход: комплексная матрица Y_bus размера n_bus × n_bus
function Ybus = build_ybus_incidence(n_bus, A_ob, Y_br, Y_shunt)
  % диагональная матрица проводимостей ветвей (7.45)
  Ybr_diag = diag(Y_br);
  % формирование Y_bus по формуле (7.51)
  Ybus = A_ob' * Ybr_diag * A_ob + diag(Y_shunt);
end
