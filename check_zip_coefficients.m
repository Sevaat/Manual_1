%проверка нормировки коэффициентов ZIP-модели
%возвращает 1, если суммы коэффициентов равны 1, иначе 0
%на вход передается вектор коэффициентов [zp, ip, pp, zq, iq, pq]
function ok = check_zip_coefficients(zip)
  zp = zip(1); ip = zip(2); pp = zip(3);
  zq = zip(4); iq = zip(5); pq = zip(6);
  %суммы коэффициентов для активной и реактивной мощности
  sum_p = zp + ip + pp;
  sum_q = zq + iq + pq;
  %проверка нормировки с допуском 1e-6 (условие 6.6)
  ok = (abs(sum_p - 1) < 1e-6) && (abs(sum_q - 1) < 1e-6);
end
