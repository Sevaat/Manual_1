% Решение СЛАУ методом Гаусса с частичным выбором ведущего элемента
% на вход передаются:
%   A — матрица коэффициентов размера n × n (комплексная)
%   b — вектор правых частей размера n × 1 (комплексный)
% на выход:
%   x — вектор решения размера n × 1
function x = gauss_solve(A, b)
  n = length(b);
  % расширенная матрица
  Ab = [A, b];

  % === Прямой ход ===
  for k = 1:n-1
    % частичный выбор ведущего элемента
    [~, p] = max(abs(Ab(k:n, k)));
    p = p + k - 1;
    if p ~= k
      Ab([k, p], :) = Ab([p, k], :);  % перестановка строк
    end
    % проверка на вырожденность
    if abs(Ab(k, k)) < 1e-14
      error('Матрица вырождена или близка к вырожденной');
    end
    % исключение
    for i = k+1:n
      m = Ab(i, k) / Ab(k, k);
      Ab(i, k:n+1) = Ab(i, k:n+1) - m * Ab(k, k:n+1);
    end
  end

  % === Обратный ход ===
  x = zeros(n, 1);
  for i = n:-1:1
    x(i) = (Ab(i, n+1) - Ab(i, i+1:n) * x(i+1:n)) / Ab(i, i);
  end
end
