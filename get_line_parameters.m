%ключевое слово function, название переменной, которое возвращается
%если переменных несколько, необходимо их обернуть в [] через запятую
%на вход необходимо передать следующий массив, содержащий данные линии:
%line = [rho, n_c, n, F_al, F_st, L, D]
%в учебных расчётах G_л мало и принимается равной нулю
function [R, X, B] = get_line_parameters(line)
  rho = line(1);
  n_c = line(2);
  n = line(3);
  F_al = line(4);
  F_st = line(5);
  L = line(6);
  D = line(7);
  %расчет погонного активного сопротивления в Ом/км
  r_0 = 1 / n * rho / F_al;
  %расчет активного сопротивления в Ом
  R = r_0 * L / n_c;
  %упрощенный (приближенный) расчет радиуса провода в мм
  %ВНИМАНИЕ: для сталеалюминиевых проводов (АС) наружный диаметр
  %не определяется суммарным сечением из-за конструкции повивки.
  %Погрешность может составлять 10-15%. Для точных расчётов
  %используйте справочный диаметр провода (например, АС 240/32:
  %наружный диаметр 21,6 мм, радиус 10,8 мм).
  r = sqrt((F_al + F_st) / pi);
  %расчет погонного реактивного сопротивления в Ом/км
  x_0 = 0.144 * log10(D / r) + 0.0157;
  %расчет реактивного сопротивления в Ом
  X = x_0 * L / n_c;
  %расчет погонной ёмкостной проводимости в См/км
  b_0 = 7.58E-6 / log10(D / r);
  %расчет ёмкостной проводимости в См (общей: начало линии + конец линии)
  B = b_0 * L * n_c;
end
