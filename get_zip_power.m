%расчет мощности нагрузки по ZIP-модели
%на вход передаются:
% P0  — номинальная активная мощность нагрузки, Вт
% Q0  — номинальная реактивная мощность нагрузки, вар
% U   — фактическое напряжение в узле, В
% U0  — номинальное (базисное) напряжение нагрузки, В
% zip — вектор коэффициентов [zp, ip, pp, zq, iq, pq]
function [P, Q] = get_zip_power(P0, Q0, U, U0, zip)
  zp = zip(1);
  ip = zip(2);
  pp = zip(3);
  zq = zip(4);
  iq = zip(5);
  pq = zip(6);
  %отношение напряжения в относительных единицах
  u = U / U0;
  %активная мощность по ZIP-модели, Вт (выражение 6.4)
  P = P0 * (zp * u^2 + ip * u + pp);
  %реактивная мощность по ZIP-модели, вар (выражение 6.5)
  Q = Q0 * (zq * u^2 + iq * u + pq);
end
