% Линейный расчёт установившегося режима
% Сеть из 3 узлов: узел 1 — источник, узлы 2,3 — нагрузки

% === Исходные данные ===
U1 = 110e3;                    % напряжение источника, В
Z12 = 3 + 1i*10;              % сопротивление линии 1-2, Ом
Z23 = 5 + 1i*15;              % сопротивление линии 2-3, Ом
I_load2 = 100 - 1i*50;        % ток нагрузки узла 2, А
I_load3 = 80 - 1i*30;         % ток нагрузки узла 3, А

% === Формирование матрицы проводимостей ===
y12 = 1 / Z12;                % проводимость линии 1-2
y23 = 1 / Z23;                % проводимость линии 2-3

% Полная матрица Y_bus (3x3)
Ybus_full = [ y12,       -y12,       0;
             -y12,  y12 + y23,     -y23;
              0,        -y23,       y23];

% === Редукция: исключение узла 1 ===
Yred = Ybus_full(2:3, 2:3);   % редуцированная матрица 2x2
I_red = [-I_load2; -I_load3] - Ybus_full(2:3, 1) * U1;

% === Решение методом Гаусса ===
U_23_gauss = gauss_solve(Yred, I_red);

% === Решение матричным методом ===
Zred = inv(Yred);
U_23_matrix = Zred * I_red;

% === Решение оператором \ ===
U_23_slash = Yred \ I_red;

% === Вывод результатов ===
U_all = [U1; U_23_slash];
fprintf('Напряжения узлов:\n');
for i = 1:3
  fprintf('  Узел %d: |U| = %.2f кВ, угол = %.3f град\n', ...
          i, abs(U_all(i))/1e3, angle(U_all(i))*180/pi);
end

% === Проверка: сравнение методов ===
fprintf('\nМакс. разность Гаусс/матричный: %.2e В\n', ...
        max(abs(U_23_gauss - U_23_matrix)));
fprintf('Макс. разность Гаусс/оператор\\: %.2e В\n', ...
        max(abs(U_23_gauss - U_23_slash)));
