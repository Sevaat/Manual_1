% Пример формирования матрицы Y_bus для сети из 3 узлов
% Узел 1 — источник, узел 2 — распределительный,
% узел 3 — нагрузка после двухобмоточного трансформатора

% количество узлов
n_bus = 3;

% шунты узлов (в данном примере отсутствуют)
Y_shunt = zeros(n_bus, 1);

% === Ветвь 1: линия электропередачи между узлами 1 и 2 ===
% параметры из таблицы 4.1
branches(1).type = 'L';
branches(1).from = 1;
branches(1).to   = 2;
branches(1).R = 3.5;          % Ом
branches(1).X = 12.266;       % Ом
branches(1).G = 0;            % См
branches(1).B = 3.3316e-4;    % См

% === Ветвь 2: двухобмоточный трансформатор между узлами 2 и 3 ===
% параметры из таблицы 4.2
branches(2).type = 'T2';
branches(2).from = 2;
branches(2).to   = 3;
branches(2).R = 0.3546;       % Ом
branches(2).X = 9.6016;       % Ом
branches(2).G = 9.5622e-6;    % См
branches(2).B = -6.5569e-5;   % См
branches(2).U1 = 121e3;       % В (ВН)
branches(2).U2 = 10.5e3;      % В (НН)

% формирование матрицы узловых проводимостей
Ybus = build_ybus(n_bus, branches, Y_shunt);

% вывод результатов
disp('Матрица узловых проводимостей Y_bus:');
disp(Ybus);
